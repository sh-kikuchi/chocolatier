from ..models import Tag


# =========================================================
# delete_unused_tags：どのスナップにも付いていないタグを消す
# - 返すもの：消したタグの数
# - タグは全利用者で共通なので、「自分のスナップから外れた」だけでは消さない
#   → 誰のスナップにも付いていないときだけ消える
# - 呼ぶ場所：serializers/snap.py の set_snap_tags（タグを付け替えたとき）、
#             signals.py（スナップが消えたとき）
# =========================================================
def delete_unused_tags():
    # snaps__isnull=True：付いているスナップが 1 つもない（中間テーブルに行がない）タグ
    deleted, _ = Tag.objects.filter(snaps__isnull=True).delete()
    return deleted
