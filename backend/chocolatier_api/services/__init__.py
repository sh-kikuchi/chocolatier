# services/（「作業係」を置くフォルダ）
# - 実際の作業（ファイルの保存・削除、Zip の作成など）を担当する
# - HTTP のこと（request / Response / ステータスコード）は知らない作りにする
#   → View や Serializer から呼ばれて、結果を返すだけ。404 を返すかどうかは View が決める
# - 役割分担（改修案件7）
#     View（窓口）       … リクエストを受けて、各係に仕事を頼み、返事を返す
#     Serializer（翻訳係）… JSON ⇔ Python の変換と、入力チェック
#     Service（作業係）   … 実際の作業。単独でテストでき、別の場所（管理画面など）からも使える
#
#     files.py … 画像ファイルの保存・削除（以前は serializers/file.py）
#     zip.py   … Zip の作成とフォルダ名の安全化（以前は views/snap.py の SnapZipDownload の中）
# =========================================================
